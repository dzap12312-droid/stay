/** Ray casting 알고리즘으로 [lat,lon] 점이 polygon([lat,lon] 배열) 내부에 있는지 판정 */
function pointInPolygon(point, polygon) {
  const [lat, lon] = point;
  let inside = false;
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    const [latI, lonI] = polygon[i];
    const [latJ, lonJ] = polygon[j];
    const intersect = ((latI > lat) !== (latJ > lat)) &&
      (lon < (lonJ - lonI) * (lat - latI) / (latJ - latI) + lonI);
    if (intersect) inside = !inside;
  }
  return inside;
}

/**
 * 경로 좌표가 베트남 경계 안에 있는지 확인한다. 국경선 폴리곤이 단순화되어 있어
 * 국경 바로 인접 구간에서 극소수 지점이 오차로 벗어날 수 있으므로, 경로 전체 지점의
 * 2%를 넘게 벗어난 경우에만 "국경을 넘었다"고 판단한다(실제 캄보디아/라오스 우회처럼
 * 뚜렷하게 벗어나는 경우만 걸러내고, 경계선 근처의 미세한 오차는 허용).
 */
function isRouteInsideVietnam(latlngs) {
  const outside = latlngs.filter(pt => !pointInPolygon(pt, VN_BOUNDARY)).length;
  return outside / latlngs.length <= 0.02;
}

const Routing = (function () {
  const ENDPOINT = 'https://router.project-osrm.org/route/v1/driving';
  const cache = {}; // key: "lat1,lon1|lat2,lon2" -> result

  function keyOf(a, b) {
    return `${a[0].toFixed(5)},${a[1].toFixed(5)}|${b[0].toFixed(5)},${b[1].toFixed(5)}`;
  }

  function toResult(route) {
    const latlngs = route.geometry.coordinates.map(([lon, lat]) => [lat, lon]);
    return {
      latlngs,
      distanceKm: Math.round(route.distance / 100) / 10,
      durationMin: Math.round(route.duration / 60)
    };
  }

  /**
   * from, to: [lat, lon]
   * 반환: { latlngs: [[lat,lon],...], distanceKm, durationMin } 또는 실패 시 null.
   * 베트남 국경을 벗어나는 경로는 채택하지 않고, 대안 경로 중 국경 안쪽인 것을 찾는다.
   */
  async function fetchRoute(from, to) {
    const key = keyOf(from, to);
    if (cache[key]) return cache[key];

    const url = `${ENDPOINT}/${from[1]},${from[0]};${to[1]},${to[0]}?overview=full&geometries=geojson&alternatives=3`;
    try {
      const res = await fetch(url, { signal: AbortSignal.timeout(10000) });
      if (!res.ok) return null;
      const data = await res.json();
      if (!data.routes || data.routes.length === 0) return null;

      for (const route of data.routes) {
        const result = toResult(route);
        if (isRouteInsideVietnam(result.latlngs)) {
          cache[key] = result;
          return result;
        }
      }
      console.warn('[Routing] 모든 후보 경로가 베트남 국경을 벗어나 표시하지 않습니다(직선으로 대체).');
      return null;
    } catch (e) {
      console.warn('[Routing] OSRM 경로 조회 실패, 직선으로 대체합니다.', e);
      return null;
    }
  }

  return { fetchRoute };
})();
