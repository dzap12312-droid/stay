/**
 * routing.js
 * OSRM(Open Source Routing Machine) 공개 데모 서버를 이용한 실제 도로 경로 조회.
 * API Key가 필요 없는 무료 서비스이며, 업체를 선택했을 때만 1건씩 조회한다(88개를 한번에 부르지 않음).
 * 실패하거나 응답이 없으면 null을 반환하고, 호출부에서 기존 직선 연결선으로 대체한다.
 *
 * 베트남 영역 밖(예: 국경 인근에서 캄보디아를 스쳐 지나가는 경로)으로 나가는 경로는
 * 사용하지 않는다. OSRM의 alternatives 옵션으로 대안 경로를 함께 받아, 그중 베트남
 * 영역을 벗어나지 않는 첫 번째 경로만 채택한다. 전부 벗어나면 null을 반환한다.
 */

/** 두 좌표([lat,lon]) 간 직선거리(km), 최인접 공장 판단 등에 사용 */
function haversineKm(a, b) {
  const R = 6371;
  const dLat = (b[0] - a[0]) * Math.PI / 180;
  const dLon = (b[1] - a[1]) * Math.PI / 180;
  const lat1 = a[0] * Math.PI / 180;
  const lat2 = b[0] * Math.PI / 180;
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(lat1) * Math.cos(lat2) * Math.sin(dLon / 2) ** 2;
  return R * 2 * Math.atan2(Math.sqrt(h), Math.sqrt(1 - h));
}

// 공장-업체 직선거리가 이 값(km) 이상이면 실제 도로 경로 조회를 시도하지 않고
// 굵은 직선으로 대체한다. 이런 초장거리 구간은 OSRM이 라오스/캄보디아를 관통하는
// 경로만 내놓는 경우가 많아(국경 밖이라 채택 불가) 도로 경로를 신뢰할 수 없기 때문이다.
const LONG_DISTANCE_THRESHOLD_KM = 1000;

/** factories 중 supplier 좌표와 직선거리가 가장 가까운 공장을 반환 */
function nearestFactory(factories, latlng) {
  let best = null;
  let bestDist = Infinity;
  for (const f of factories) {
    const d = haversineKm([f.latitude, f.longitude], latlng);
    if (d < bestDist) { bestDist = d; best = f; }
  }
  return best;
}

